package vazkii.botania.client.patchouli;

import net.minecraft.client.Minecraft;
import net.minecraft.core.HolderLookup;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.crafting.Ingredient;
import net.minecraft.world.item.crafting.Recipe;
import net.minecraft.world.item.crafting.RecipeType;
import net.minecraft.world.level.Level;

import vazkii.botania.api.BotaniaAPI;
import vazkii.botania.common.crafting.BotaniaRecipeTypes;
import vazkii.botania.common.helper.IngredientHelper;
import vazkii.botania.xplat.XplatAbstractions;
import vazkii.patchouli.api.IVariable;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

public class PatchouliUtils {
	private static boolean crafttweakerInfoNote = false;
	private static boolean inVisualizer;

	/**
	 * Gets a recipe of a specified type and ID, and replaces the namespace
	 * with {@code crafttweaker} to try and find replacements if the recipe doesn't exist.
	 *
	 * If the recipe has no replacement, it will be logged.
	 */
	public static <T extends Recipe<?>> T getRecipe(Level level, RecipeType<T> type, Identifier id) {
		Map<Identifier, T> map = recipes(level, type);
		T r = map.get(id);
		if (r != null) {
			return r;
		}
		r = map.get(Identifier.fromNamespaceAndPath("crafttweaker", id.getPath()));
		if (r != null) {
			return r;
		}
		r = map.get(Identifier.fromNamespaceAndPath("crafttweaker", "autogenerated/" + id.getNamespace() + "." + id.getPath()));
		if (r != null) {
			return r;
		}

		BotaniaAPI.LOGGER.warn("Template references nonexistent recipe {} of type {}", id, type);
		if (!crafttweakerInfoNote) {
			crafttweakerInfoNote = true;
			if (XplatAbstractions.INSTANCE.isModLoaded("crafttweaker")) {
				BotaniaAPI.LOGGER.info("""
					To add a recipe that replaces a builtin recipe with CT,\s
					add one with the same type, named the same as the path of the missing recipe.
					eg. for recipe {}, add a recipe named "{}".""", id, id.getPath());
			}
		}
		return null;
	}

	/**
	 * In MC 26.1 clients have no {@code RecipeManager} of their own, so
	 * {@code BotaniaRecipeTypes.getRecipes(Level, type)} returns an empty map there. Patchouli 26.1
	 * keeps the recipe holders synchronized from the server in {@code ClientRecipes}; fall back to
	 * that cache whenever the level cannot supply recipes. The {@link ClientRecipeLookup}
	 * indirection keeps Patchouli's client classes off the dedicated-server class path.
	 */
	private static <T extends Recipe<?>> Map<Identifier, T> recipes(Level level, RecipeType<T> type) {
		Map<Identifier, T> fromLevel = BotaniaRecipeTypes.getRecipes(level, type);
		return fromLevel.isEmpty() ? ClientRecipeLookup.byType(type) : fromLevel;
	}

	/**
	 * Get all recipes of the specified type that belong to the specified recipe group.
	 */
	public static <T extends Recipe<?>> List<T> getRecipeGroup(RecipeType<T> type, String group) {
		Map<Identifier, T> map = recipes(Minecraft.getInstance().level, type);
		List<T> list = new ArrayList<>();
		for (T value : map.values()) {
			if (group.equals(value.group())) {
				list.add(value);
			}
		}
		if (list.isEmpty()) {
			BotaniaAPI.LOGGER.warn("Template references empty group {} of recipe type {}", group, type);
		}
		return list;
	}

	/**
	 * @return The stacks matched by the given ingredient, for display purposes.
	 */
	public static List<ItemStack> getStacks(Ingredient ingredient) {
		// IngredientHelper.EMPTY is an unbound named tag in MC 26.1. Calling isEmpty() or items()
		// on it throws "Tag ... can't be dereferenced during construction" while book contents
		// are compiled, so compare by identity before touching the holder set.
		if (ingredient == null || ingredient == IngredientHelper.EMPTY) {
			return List.of(ItemStack.EMPTY);
		}
		return ingredient.items().map(ItemStack::new).collect(Collectors.toList());
	}

	/**
	 * Combines the ingredients, returning the first matching stack of each, then the second stack of each, etc.
	 * looping back ingredients that run out of matched stacks, until the ingredients reach the length
	 * of the longest ingredient in the recipe set.
	 *
	 * @param ingredients           List of ingredients in the specific slot
	 * @param longestIngredientSize Longest ingredient in the entire recipe
	 * @return Serialized Patchouli ingredient string
	 */
	public static IVariable interweaveIngredients(List<Ingredient> ingredients, int longestIngredientSize, HolderLookup.Provider registries) {
		if (ingredients.size() == 1) {
			return IVariable.wrapList(getStacks(ingredients.get(0)).stream().map(stack -> IVariable.from(stack, registries)).collect(Collectors.toList()), registries);
		}

		List<ItemStack> empty = List.of(ItemStack.EMPTY);
		List<List<ItemStack>> stacks = new ArrayList<>();
		for (Ingredient ingredient : ingredients) {
			stacks.add(getStacks(ingredient));
		}
		List<IVariable> list = new ArrayList<>(stacks.size() * longestIngredientSize);
		for (int i = 0; i < longestIngredientSize; i++) {
			for (List<ItemStack> stack : stacks) {
				list.add(IVariable.from(stack.get(i % stack.size()), registries));
			}
		}
		return IVariable.wrapList(list, registries);
	}

	/**
	 * Overload of the method above that uses the provided list's longest ingredient size.
	 */
	public static IVariable interweaveIngredients(List<Ingredient> ingredients, HolderLookup.Provider registries) {
		return interweaveIngredients(ingredients, ingredients.stream().mapToInt(ingr -> getStacks(ingr).size()).max().orElse(1), registries);
	}

	/**
	 * Workaround for Patchouli limitation - Allow block entity-rendered blocks to detect being rendered in
	 * a multiblock visualization and switch to block model rendering to actually be visible.
	 */
	public static boolean isInVisualizer() {
		return inVisualizer;
	}

	public static void setInVisualizer(boolean inVisualization) {
		PatchouliUtils.inVisualizer = inVisualization;
	}
}
